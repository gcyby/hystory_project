function showInfo(key) {
    document.getElementById('placeholder').style.display = 'none';
    document.getElementById('poi-content').style.display = 'block';
    document.getElementById('poi-name').innerText = locationsData[key].title;
    document.getElementById('poi-text').innerText = locationsData[key].text;
}

function initMap() {
    // 1. Отключаем дефолтный копирайт Яндекса/Leaflet с помощью свойства attributionControl: false
    const map = L.map('map-container', {
        attributionControl: false 
    }).setView([64.7, 38.7], 8);

    // 2. Подключаем карту OpenStreetMap
    L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
        maxZoom: 18
    }).addTo(map);

    // 3. Добавляем свой чистый, аккуратный копирайт без флагов и лишних ссылок
    L.control.attribution({
        prefix: 'Цифровой путеводитель «Летний берег Белого моря» | © OpenStreetMap'
    }).addTo(map);

    // Рисуем наши кастомные маркеры (этот блок остается без изменений)
    Object.keys(locationsData).forEach(key => {
        const item = locationsData[key];

        const circleMarker = L.circleMarker(item.coordinates, {
            radius: 8,
            fillColor: '#2C4A5E',
            color: '#FFFFFF',
            weight: 2,
            opacity: 1,
            fillOpacity: 1
        }).addTo(map);

        circleMarker.on('click', function () {
            showInfo(key);
            
            map.eachLayer(layer => {
                if (layer instanceof L.CircleMarker) {
                    layer.setStyle({ fillColor: '#2C4A5E' });
                }
            });
            this.setStyle({ fillColor: '#8C6D53' });
        });
    });
}

// Запуск карты
window.onload = () => {
    initMap();
};